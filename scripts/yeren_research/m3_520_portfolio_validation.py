    PREREGISTERED_END_DATE,
    PREREGISTERED_SPLIT_DATE,
    PREREGISTERED_START_DATE,
    PREREGISTERED_STOP_DAYS,
    CostModel,
    TradeE,
    _touched_dates_with_buffer,
    build_st_mask,
    build_universe,
    load_constraints,
    load_st_timeline,
