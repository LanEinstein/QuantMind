"""Portfolio-level validation for the 520 rule (preregistered, deterministic).

Locked by `docs/research/yeren-system/m3-520-portfolio-validation-
preregistration-2026-08-22.md`. The rule semantics, gating, and price
conventions are candidate E's, reused verbatim; this module adds only the
capital layer: 10% total-exposure cap (owner-authorized cross-card
citation), 5 concurrent slots x 2% each (researcher-added), 1,000,000 CNY
initial capital, actual broker fees (commission 0.015% with a 5 CNY floor).

The trade stream is generated by the very same `simulate_trades_e` that
produced the published candidate-E results, so the portfolio layer can only
decide which mechanical signals to take -- never when, or at what price.
Sizing and affordability are settled at each fill (the only moment the true
fill price exists); slot / duplicate / exposure checks run at the decision
close using that day's marks. Everything is a deterministic replay: no
random numbers, no seeds.

Research-only. No playbook, simulator order, broker instruction, or
execution service is created. `real_broker_orders=False` always.
"""

